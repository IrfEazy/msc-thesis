#!/usr/bin/env python3
"""Generate and push Kaggle bundles (code dataset, data dataset, one kernel per notebook).

Everything (datasets, kernels, paths, env, links, accelerator) comes from the `[kaggle]` table
and the `[notebooks.kaggle]` subtables of the manifest (default: experiments.toml); this script
only executes it. Kaggle credentials are never read: the Kaggle CLI uses the user's own config.

  uv run python scripts/kaggle_bundle.py build [--out DIR] [--only NAME] [--smoke]
  uv run python scripts/kaggle_bundle.py push [--out DIR] [--only NAME] [--smoke] [--dry-run]
  uv run python scripts/kaggle_bundle.py status [--only NAME] [--smoke]
  uv run python scripts/kaggle_bundle.py fetch [--only NAME] [--smoke] [--out DIR]
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import time
import sys
from pathlib import Path

import nbformat

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_notebooks as rn  # noqa: E402  (manifest loader, REPO, revision)

REPO = rn.REPO
BOOTSTRAP_HEADER = "# BOOTSTRAP (generated by scripts/kaggle_bundle.py; do not edit)"
SMOKE_SUFFIX = "-smoke"
PLACEHOLDER = re.compile(r"\{input:([^{}]+)\}")

# Generic bootstrap, executed on Kaggle. CFG (from the manifest) is prepended by the builder.
BOOTSTRAP_BODY = r'''
import hashlib, importlib, os, shutil, subprocess, sys, re
from pathlib import Path

INPUT_ROOT = Path(os.environ.get("KAGGLE_INPUT_ROOT", "/kaggle/input"))
WORKING_ROOT = Path(os.environ.get("KAGGLE_WORKING_ROOT", "/kaggle/working"))
TMP_ROOT = Path(os.environ.get("KAGGLE_TMP_ROOT", "/kaggle/tmp"))
try:
    TMP_ROOT.mkdir(parents=True, exist_ok=True)
    print("tmp root:", TMP_ROOT)
except OSError as exc:
    import tempfile
    TMP_ROOT = Path(tempfile.gettempdir())
    print(f"tmp root: {TMP_ROOT} (fallback; configured root unusable: {exc})")
REPO_DIR = TMP_ROOT / "msc-thesis"


def find_mount(slug, max_depth=3):
    hits = []
    base_depth = len(INPUT_ROOT.parts)
    for root, dirs, _ in os.walk(INPUT_ROOT):
        depth = len(Path(root).parts) - base_depth
        if depth >= max_depth:
            dirs[:] = []
        for d in list(dirs):
            if d == slug:
                hits.append(Path(root) / d)
                dirs.remove(d)
    if len(hits) != 1:
        raise RuntimeError(f"dataset mount for {slug!r}: expected 1 match under {INPUT_ROOT}, found {hits}")
    return hits[0]


MOUNTS = {s: find_mount(s) for s in CFG["slugs"]}


def resolve(text):
    text = text.replace("{repo}", str(REPO_DIR)).replace("{working}", str(WORKING_ROOT))
    return re.sub(r"\{input:([^{}]+)\}", lambda m: str(MOUNTS[m.group(1)]), text)


if REPO_DIR.exists() or REPO_DIR.is_symlink():
    shutil.rmtree(REPO_DIR)
shutil.copytree(MOUNTS[CFG["code_slug"]], REPO_DIR, symlinks=True)

if os.environ.get("BUNDLE_SKIP_PIP") != "1":
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-r", str(REPO_DIR / "requirements-kaggle.txt")], check=True)

for rel, target in CFG["links"].items():
    link = REPO_DIR / rel
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.exists() or link.is_symlink():
        raise RuntimeError(f"link path already exists: {link}")
    link.symlink_to(resolve(target), target_is_directory=True)

for rel in sorted(CFG["outputs_dirs"]):
    out = WORKING_ROOT / rel
    out.mkdir(parents=True, exist_ok=True)
    link = REPO_DIR / rel
    if link.exists() or link.is_symlink():
        continue  # already reachable through a parent link
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(out, target_is_directory=True)

for k, v in CFG["env"].items():
    os.environ[k] = resolve(v)

CWD = Path(resolve(CFG["cwd"]))
for p in (str(REPO_DIR),):
    if p in sys.path:
        sys.path.remove(p)
    sys.path.insert(0, p)
os.chdir(CWD)

for name in CFG["block_imports"]:
    sys.modules[name] = None  # also works for dotted names such as google.colab
    try:
        importlib.import_module(name)
    except ImportError:
        pass
    else:
        raise AssertionError(f"{name} is still importable")


def _version(mod):
    try:
        m = importlib.import_module(mod)
        extra = f" cuda={m.cuda.is_available()}" if mod == "torch" else ""
        return f"{mod}={getattr(m, '__version__', '?')}{extra}"
    except Exception as exc:
        return f"{mod}=unavailable({type(exc).__name__})"


print("BOOTSTRAP OK", "revision=" + CFG["revision"], "notebook_sha256=" + CFG["source_sha256"],
      "cwd=" + str(CWD), "blocked=" + (",".join(CFG["block_imports"]) or "none"),
      *[_version(m) for m in ("numpy", "pandas", "sklearn", "torch", "xgboost", "sentence_transformers")])
'''

SMOKE_BODY = r'''
missing = []
for k, v in CFG["env"].items():
    if "{input:" in v:
        if not Path(resolve(v)).exists():
            missing.append(f"env {k}={resolve(v)}")
    elif v.startswith("{repo}") or v.startswith("{working}"):
        if not Path(resolve(v)).parent.exists():
            missing.append(f"env {k} parent of {resolve(v)}")
for rel, target in CFG["links"].items():
    if not (REPO_DIR / rel).exists():
        missing.append(f"link {rel} -> {resolve(target)}")
assert not missing, "missing: " + "; ".join(missing)
for mod in CFG["modules"]:
    importlib.import_module(mod)
    print("imported", mod)
for k in CFG["env"]:
    print(k, "=", os.environ[k])
print("SMOKE OK")
'''


# ---------------------------------------------------------------- manifest

def kaggle_config(manifest):
    cfg = manifest.get("kaggle")
    if not cfg:
        sys.exit("manifest has no [kaggle] table")
    for key in ("owner", "code_dataset", "data_dataset", "code_paths", "data", "build_dir"):
        if key not in cfg:
            sys.exit(f"[kaggle]: missing {key!r}")
    return cfg


def selected(manifest, only):
    out = [n for n in manifest["notebooks"]
           if n["target"] == "kaggle" and not n.get("blocked") and "kaggle" in n]
    if only:
        out = [n for n in out if n["name"] == only]
        if not out:
            sys.exit(f"no runnable Kaggle notebook named {only!r}")
    return out


def kernel_slug(entry, smoke):
    return entry["kaggle"]["slug"] + (SMOKE_SUFFIX if smoke else "")


def code_modules(cfg):
    mods = []
    for p in cfg["code_paths"]:
        path = Path(p)
        if len(path.parts) == 1:
            if path.suffix == ".py":
                mods.append(path.stem)
            elif (REPO / path).is_dir() and (REPO / path / "__init__.py").exists():
                mods.append(path.name)
    return mods


# ---------------------------------------------------------------- build

def copy_py_tree(src, dest):
    for f in sorted(src.rglob("*.py")):
        if "__pycache__" in f.parts:
            continue
        target = dest / f.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, target)


def copy_entry(src, dest, py_only):
    if not src.exists():
        sys.exit(f"missing source path: {src.relative_to(REPO) if src.is_relative_to(REPO) else src}")
    if src.is_dir():
        if py_only:
            copy_py_tree(src, dest)
        else:
            shutil.copytree(src, dest, dirs_exist_ok=True)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2) + "\n")


def dataset_meta(owner, slug, license_name):
    return {"title": slug, "id": f"{owner}/{slug}", "licenses": [{"name": license_name}]}


def build_datasets(cfg, out):
    code = out / "datasets" / "code"
    data = out / "datasets" / "data"
    for d in (code, data):
        if d.exists():
            shutil.rmtree(d)
    for p in cfg["code_paths"]:
        copy_entry(REPO / p, code / p, py_only=True)
    write_json(code / "dataset-metadata.json", dataset_meta(cfg["owner"], cfg["code_dataset"], cfg.get("code_license", "CC0-1.0")))
    for item in cfg["data"]:
        copy_entry(REPO / item["src"], data / item["dest"], py_only=False)
    write_json(data / "dataset-metadata.json", dataset_meta(cfg["owner"], cfg["data_dataset"], cfg.get("data_license", "unknown")))


def check_placeholders(entry, slugs):
    texts = [entry["kaggle"].get("cwd", "")] + [str(v) for v in entry.get("env", {}).values()] \
        + [str(v) for v in entry["kaggle"].get("links", {}).values()]
    for t in texts:
        for s in PLACEHOLDER.findall(t):
            if s not in slugs:
                sys.exit(f"{entry['name']}: {{input:{s}}} is not an attached dataset ({sorted(slugs)})")


def bootstrap_source(cfg, entry, cfg_extra):
    k = entry["kaggle"]
    datasets = k["datasets"]
    slugs = [d.split("/", 1)[1] for d in datasets]
    check_placeholders(entry, slugs)
    code_ref = f"{cfg['owner']}/{cfg['code_dataset']}"
    for need in (code_ref, f"{cfg['owner']}/{cfg['data_dataset']}"):
        if need not in datasets:
            sys.exit(f"{entry['name']}: datasets must include {need}")
    src = (REPO / entry["path"]).read_bytes()
    conf = {
        "slugs": slugs, "code_slug": cfg["code_dataset"], "links": k.get("links", {}),
        "outputs_dirs": k.get("outputs_dirs", []), "env": {kk: str(v) for kk, v in entry.get("env", {}).items()},
        "cwd": k.get("cwd", "{repo}"), "block_imports": k.get("block_imports", []),
        "revision": rn.revision(), "source_sha256": hashlib.sha256(src).hexdigest(),
        **cfg_extra,
    }
    return f"{BOOTSTRAP_HEADER}\nimport json\nCFG = json.loads({json.dumps(conf)!r})\n" + BOOTSTRAP_BODY


def build_kernel(cfg, entry, out, smoke):
    k = entry["kaggle"]
    slug = kernel_slug(entry, smoke)
    kdir = out / "kernels" / slug
    if kdir.exists():
        shutil.rmtree(kdir)
    cells = [nbformat.v4.new_code_cell(
        bootstrap_source(cfg, entry, {"modules": code_modules(cfg)}))]
    if smoke:
        cells.append(nbformat.v4.new_code_cell(SMOKE_BODY.lstrip("\n")))
    else:
        nb = nbformat.read(REPO / entry["path"], as_version=4)
        for c in nb.cells:
            if c.cell_type == "code":
                c.outputs = []
                c.execution_count = None
            cells.append(c)
    nb_out = nbformat.v4.new_notebook(cells=cells)
    nb_out.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python", "name": "python3"}
    nb_out.metadata["language_info"] = {"name": "python"}
    kdir.mkdir(parents=True)
    code_file = f"{slug}.ipynb"
    nbformat.write(nb_out, kdir / code_file)
    write_json(kdir / "kernel-metadata.json", {
        "id": f"{cfg['owner']}/{slug}", "title": slug, "code_file": code_file,
        "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": k.get("accelerator") == "gpu", "enable_tpu": False,
        "enable_internet": bool(k.get("internet", True)),
        "dataset_sources": k["datasets"], "competition_sources": [], "kernel_sources": [],
        "model_sources": [],
    })
    return kdir


def cmd_build(args, manifest, cfg):
    out = Path(args.out or cfg["build_dir"])
    out = out if out.is_absolute() else REPO / out
    entries = selected(manifest, args.only)
    build_datasets(cfg, out)
    for e in entries:
        print("kernel:", build_kernel(cfg, e, out, args.smoke).relative_to(out))
    print(f"built {len(entries)} kernel(s) and 2 datasets in {out}")
    return 0


# ---------------------------------------------------------------- push / status / fetch

def run_cmd(cmd, dry):
    print("$", " ".join(cmd))
    if dry:
        return 0
    return subprocess.run(cmd).returncode


def dataset_exists(ref):
    r = subprocess.run(["kaggle", "datasets", "status", ref], capture_output=True, text=True)
    out = r.stdout.strip().lower()
    if r.returncode == 0 and out in ("ready", "pending", "queued", "running", "error"):
        return True
    detail = (r.stderr.strip() or r.stdout.strip()).splitlines()
    print(f"dataset status for {ref} failed (rc={r.returncode}): {detail[-1] if detail else 'no output'}; "
          "assuming absent (will try create)")
    return False


def wait_dataset_ready(ref, timeout, interval=15):
    start = time.monotonic()
    while True:
        r = subprocess.run(["kaggle", "datasets", "status", ref], capture_output=True, text=True)
        text = (r.stdout.strip() or r.stderr.strip())
        if r.returncode == 0 and "ready" in r.stdout.lower():
            print(f"dataset {ref} ready")
            return True
        elapsed = int(time.monotonic() - start)
        if elapsed >= timeout:
            return False
        print(f"waiting for {ref}: {text or 'no output'} ({elapsed}s/{timeout}s)")
        time.sleep(interval)


def cmd_push(args, manifest, cfg):
    out = Path(args.out or cfg["build_dir"])
    out = out if out.is_absolute() else REPO / out
    entries = selected(manifest, args.only)
    if not (out / "datasets").is_dir():
        sys.exit(f"nothing built in {out}; run `build` first")
    sha = rn.git("rev-parse", "--short", "HEAD") or "unknown"
    for sub, slug in (("code", cfg["code_dataset"]), ("data", cfg["data_dataset"])):
        ref, path = f"{cfg['owner']}/{slug}", str(out / "datasets" / sub)
        if args.dry_run:
            print("# create if absent, otherwise version:")
            run_cmd(["kaggle", "datasets", "create", "-p", path, "-r", "zip"], True)
            run_cmd(["kaggle", "datasets", "version", "-p", path, "-m", sha, "-r", "zip"], True)
            continue
        cmd = (["kaggle", "datasets", "version", "-p", path, "-m", sha, "-r", "zip"]
               if dataset_exists(ref) else ["kaggle", "datasets", "create", "-p", path, "-r", "zip"])
        if run_cmd(cmd, False):
            return 1
        timeout = int(cfg.get("dataset_ready_timeout", 900))
        if not wait_dataset_ready(ref, timeout):
            print(f"error: dataset {ref} not ready after {timeout}s; aborting before kernel pushes", file=sys.stderr)
            return 1
    for e in entries:
        kdir = out / "kernels" / kernel_slug(e, args.smoke)
        if not kdir.is_dir():
            sys.exit(f"{kdir} not built; run `build{' --smoke' if args.smoke else ''}` first")
        cmd = ["kaggle", "kernels", "push", "-p", str(kdir)]
        if cfg.get("accelerator"):
            cmd += ["--accelerator", cfg["accelerator"]]
        if run_cmd(cmd, args.dry_run):
            return 1
    return 0


def cmd_status(args, manifest, cfg):
    rc = 0
    for e in selected(manifest, args.only):
        rc |= run_cmd(["kaggle", "kernels", "status", f"{cfg['owner']}/{kernel_slug(e, args.smoke)}"], False)
    return rc


def cmd_fetch(args, manifest, cfg):
    base = Path(args.out or "runs/kaggle")
    base = base if base.is_absolute() else REPO / base
    rc = 0
    for e in selected(manifest, args.only):
        slug = kernel_slug(e, args.smoke)
        dest = base / slug
        dest.mkdir(parents=True, exist_ok=True)
        rc |= run_cmd(["kaggle", "kernels", "output", f"{cfg['owner']}/{slug}", "-p", str(dest)], False)
    return rc


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(rn.DEFAULT_MANIFEST))
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn in (("build", cmd_build), ("push", cmd_push), ("status", cmd_status), ("fetch", cmd_fetch)):
        p = sub.add_parser(name)
        p.add_argument("--only")
        p.add_argument("--smoke", action="store_true", help="smoke kernels (suffix -smoke)")
        if name in ("build", "push", "fetch"):
            p.add_argument("--out")
        if name == "push":
            p.add_argument("--dry-run", action="store_true")
        p.set_defaults(fn=fn)
    args = ap.parse_args(argv)
    manifest = rn.load_manifest(args.manifest)
    return args.fn(args, manifest, kaggle_config(manifest))


if __name__ == "__main__":
    sys.exit(main())

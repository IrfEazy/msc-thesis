# ---------------------------------------------------------------- manifest

def kaggle_config(manifest):
    cfg = manifest.get("kaggle")
    if not cfg:
        sys.exit("manifest has no [kaggle] table")
    for key in ("owner", "code_dataset", "data_dataset", "code_paths", "data", "build_dir"):
        if key not in cfg:
            sys.exit(f"[kaggle]: missing {key!r}")
    return cfg


def selected(manifest, only):
    out = [n for n in manifest["notebooks"]
           if n["target"] == "kaggle" and not n.get("blocked") and "kaggle" in n]
    if only:
        out = [n for n in out if n["name"] == only]
        if not out:
            sys.exit(f"no runnable Kaggle notebook named {only!r}")
    return out


def kernel_slug(entry, smoke):
    return entry["kaggle"]["slug"] + (SMOKE_SUFFIX if smoke else "")


def is_gpu(entry):
    """GPU kernel iff the notebook's accelerator is "gpu"; "none" or absent means a CPU kernel."""
    acc = str(entry["kaggle"].get("accelerator", "none")).lower()
    if acc not in ("gpu", "none"):
        sys.exit(f"{entry['name']}: accelerator must be 'gpu' or 'none', got {acc!r}")
    return acc == "gpu"


def source_refs(cfg, manifest, entry):
    """`kernels` of the entry as owner/slug refs (manifest slugs are owner-prefixed, owner/slug kept)."""
    own = {n["kaggle"]["slug"] for n in manifest["notebooks"] if "kaggle" in n}
    refs = []
    for r in entry["kaggle"].get("kernels", []):
        if "/" not in r:
            if r not in own:
                sys.exit(f"{entry['name']}: kernels entry {r!r} is not a manifest kernel slug (use owner/slug for others)")
            r = f"{cfg['owner']}/{r}"
        if r == f"{cfg['owner']}/{entry['kaggle']['slug']}":
            sys.exit(f"{entry['name']}: kernel cannot list itself in kernels")
        refs.append(r)
    return refs


def check_unique_slugs(manifest):
    seen = {}
    for n in manifest["notebooks"]:
        if "kaggle" in n:
            slug = n["kaggle"]["slug"]
            if slug in seen:
                sys.exit(f"kernel slug {slug!r} used by both {seen[slug]!r} and {n['name']!r}")
            seen[slug] = n["name"]


def code_modules(cfg):
    mods = []
    for p in cfg["code_paths"]:
        path = Path(p)
        if len(path.parts) == 1:
            if path.suffix == ".py":
                mods.append(path.stem)
            elif (REPO / path).is_dir() and (REPO / path / "__init__.py").exists():
                mods.append(path.name)
    return mods


# ---------------------------------------------------------------- build

def copy_py_tree(src, dest):
    for f in sorted(src.rglob("*.py")):
        if "__pycache__" in f.parts:
            continue
        target = dest / f.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, target)


def copy_entry(src, dest, py_only):
    if not src.exists():
        sys.exit(f"missing source path: {src.relative_to(REPO) if src.is_relative_to(REPO) else src}")
    if src.is_dir():
        if py_only:
            copy_py_tree(src, dest)
        else:
            shutil.copytree(src, dest, dirs_exist_ok=True)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2) + "\n")


def check_title(title, what):
    """Exit with a clear error if `title` is outside Kaggle's title length limits.

    >>> check_title("a" * 50, "kernel x")
    >>> check_title("a" * 51, "kernel x")
    Traceback (most recent call last):
    SystemExit: error: kernel x: Kaggle title 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa' has 51 characters; allowed 5..50. Shorten the slug.
    >>> check_title("abcd", "dataset y")
    Traceback (most recent call last):
    SystemExit: error: dataset y: Kaggle title 'abcd' has 4 characters; allowed 5..50. Shorten the slug.
    """
    lo, hi = KAGGLE_TITLE_LEN
    if not lo <= len(title) <= hi:
        sys.exit(f"error: {what}: Kaggle title '{title}' has {len(title)} characters; "
                 f"allowed {lo}..{hi}. Shorten the slug.")


def dataset_meta(owner, slug, license_name):
    check_title(slug, f"dataset {owner}/{slug}")
    return {"title": slug, "id": f"{owner}/{slug}", "licenses": [{"name": license_name}]}


def build_datasets(cfg, out):
    code = out / "datasets" / "code"
    data = out / "datasets" / "data"
    for d in (code, data):
        if d.exists():
            shutil.rmtree(d)
    for p in cfg["code_paths"]:
        copy_entry(REPO / p, code / p, py_only=True)
    write_json(code / "dataset-metadata.json", dataset_meta(cfg["owner"], cfg["code_dataset"], cfg.get("code_license", "CC0-1.0")))
    for item in cfg["data"]:
        copy_entry(REPO / item["src"], data / item["dest"], py_only=False)
    write_json(data / "dataset-metadata.json", dataset_meta(cfg["owner"], cfg["data_dataset"], cfg.get("data_license", "unknown")))


def check_placeholders(entry, slugs):
    texts = [entry["kaggle"].get("cwd", "")] + [str(v) for v in entry.get("env", {}).values()] \
        + [str(v) for v in entry["kaggle"].get("links", {}).values()] \
        + [a for c in entry["kaggle"].get("setup_commands", []) for a in c]
    for t in texts:
        for s in PLACEHOLDER.findall(t):
            if s not in slugs:
                sys.exit(f"{entry['name']}: {{input:{s}}} is not an attached dataset or kernel ({sorted(slugs)})")


def setup_commands(cfg, entry):
    out = []
    for where, lst in (("[kaggle]", cfg.get("setup_commands", [])), (entry["name"], entry["kaggle"].get("setup_commands", []))):
        if not isinstance(lst, list):
            sys.exit(f"{entry['name']}: setup_commands in {where} must be a list of argv lists")
        for c in lst:
            if not (isinstance(c, list) and c and all(isinstance(a, str) for a in c)):
                sys.exit(f"{entry['name']}: setup_commands in {where}: each command must be a non-empty list of strings, got {c!r}")
            out.append(c)
    return out


def bootstrap_source(cfg, entry, cfg_extra, sources=()):
    k = entry["kaggle"]
    datasets = k["datasets"]
    slugs = [d.split("/", 1)[1] for d in datasets] + [r.split("/", 1)[1] for r in sources]
    k = {**k, "setup_commands": setup_commands(cfg, entry)}
    check_placeholders({**entry, "kaggle": k}, slugs)
    code_ref = f"{cfg['owner']}/{cfg['code_dataset']}"
    for need in (code_ref, f"{cfg['owner']}/{cfg['data_dataset']}"):
        if need not in datasets:
            sys.exit(f"{entry['name']}: datasets must include {need}")
    src = (REPO / entry["path"]).read_bytes()
    conf = {
        "slugs": slugs, "code_slug": cfg["code_dataset"], "links": k.get("links", {}),
        "outputs_dirs": k.get("outputs_dirs", []), "env": {kk: str(v) for kk, v in entry.get("env", {}).items()},
        "cwd": k.get("cwd", "{repo}"), "block_imports": k.get("block_imports", []),
        "setup_commands": k["setup_commands"], "revision": rn.revision(), "source_sha256": hashlib.sha256(src).hexdigest(),
        **cfg_extra,
    }
    return f"{BOOTSTRAP_HEADER}\nimport json\nCFG = json.loads({json.dumps(conf)!r})\n" + BOOTSTRAP_BODY


def build_kernel(cfg, entry, out, smoke, sources=()):
    k = entry["kaggle"]
    slug = kernel_slug(entry, smoke)
    check_title(slug, f"kernel entry '{entry['name']}'")
    kdir = out / "kernels" / slug
    if kdir.exists():
        shutil.rmtree(kdir)
    cells = [nbformat.v4.new_code_cell(
        bootstrap_source(cfg, entry, {"modules": code_modules(cfg)}, sources))]
    if smoke:
        cells.append(nbformat.v4.new_code_cell(SMOKE_BODY.lstrip("\n")))
    else:
        nb = nbformat.read(REPO / entry["path"], as_version=4)
        for c in nb.cells:
            if c.cell_type == "code":
                c.outputs = []
                c.execution_count = None
            cells.append(c)
    nb_out = nbformat.v4.new_notebook(cells=cells)
    nb_out.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python", "name": "python3"}
    nb_out.metadata["language_info"] = {"name": "python"}
    kdir.mkdir(parents=True)
    code_file = f"{slug}.ipynb"
    nbformat.write(nb_out, kdir / code_file)
    write_json(kdir / "kernel-metadata.json", {
        "id": f"{cfg['owner']}/{slug}", "title": slug, "code_file": code_file,
        "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": is_gpu(entry), "enable_tpu": False,
        "enable_internet": bool(k.get("internet", True)),
        "dataset_sources": k["datasets"], "competition_sources": [], "kernel_sources": list(sources),
        "model_sources": [],
    })
    return kdir


def cmd_build(args, manifest, cfg):
    out = Path(args.out or cfg["build_dir"])
    out = out if out.is_absolute() else REPO / out
    check_unique_slugs(manifest)
    entries = selected(manifest, args.only)
    build_datasets(cfg, out)
    for e in entries:
        print("kernel:", build_kernel(cfg, e, out, args.smoke, source_refs(cfg, manifest, e)).relative_to(out))
    print(f"built {len(entries)} kernel(s) and 2 datasets in {out}")
    return 0


# ---------------------------------------------------------------- push / status / fetch

def run_cmd(cmd, dry):
    print("$", " ".join(cmd))
    if dry:
        return 0
    return subprocess.run(cmd).returncode


def dataset_exists(ref):
    r = subprocess.run(["kaggle", "datasets", "status", ref], capture_output=True, text=True)
    out = r.stdout.strip().lower()
    if r.returncode == 0 and out in ("ready", "pending", "queued", "running", "error"):
        return True
    detail = (r.stderr.strip() or r.stdout.strip()).splitlines()
    print(f"dataset status for {ref} failed (rc={r.returncode}): {detail[-1] if detail else 'no output'}; "
          "assuming absent (will try create)")
    return False


def wait_dataset_ready(ref, timeout, interval=15):
    start = time.monotonic()
    while True:
        r = subprocess.run(["kaggle", "datasets", "status", ref], capture_output=True, text=True)
        text = (r.stdout.strip() or r.stderr.strip())
        if r.returncode == 0 and "ready" in r.stdout.lower():
            print(f"dataset {ref} ready")
            return True
        elapsed = int(time.monotonic() - start)
        if elapsed >= timeout:
            return False
        print(f"waiting for {ref}: {text or 'no output'} ({elapsed}s/{timeout}s)")
        time.sleep(interval)


def cmd_push(args, manifest, cfg):
    out = Path(args.out or cfg["build_dir"])
    out = out if out.is_absolute() else REPO / out
    check_unique_slugs(manifest)
    entries = selected(manifest, args.only)
    if not (out / "datasets").is_dir():
        sys.exit(f"nothing built in {out}; run `build` first")
    if not (args.dry_run or args.force):
        check_sources_complete(cfg, manifest, entries)
    sha = rn.git("rev-parse", "--short", "HEAD") or "unknown"
    if not args.kernels_only:
        for sub, slug in (("code", cfg["code_dataset"]), ("data", cfg["data_dataset"])):
            ref, path = f"{cfg['owner']}/{slug}", str(out / "datasets" / sub)
            if args.dry_run:
                print("# create if absent, otherwise version:")
                run_cmd(["kaggle", "datasets", "create", "-p", path, "-r", "zip"], True)
                run_cmd(["kaggle", "datasets", "version", "-p", path, "-m", sha, "-r", "zip"], True)
                continue
            cmd = (["kaggle", "datasets", "version", "-p", path, "-m", sha, "-r", "zip"]
                   if dataset_exists(ref) else ["kaggle", "datasets", "create", "-p", path, "-r", "zip"])
            if run_cmd(cmd, False):
                return 1
            timeout = int(cfg.get("dataset_ready_timeout", 900))
            if not wait_dataset_ready(ref, timeout):
                print(f"error: dataset {ref} not ready after {timeout}s; aborting before kernel pushes", file=sys.stderr)
                return 1
    interval = int(cfg.get("gpu_poll_interval", 60))
    limits = {True: int(cfg.get("max_gpu_sessions", 2)),
              False: int(cfg["max_cpu_sessions"]) if "max_cpu_sessions" in cfg else None}
    pushed, failed = {True: [], False: []}, []
    wait_timeout = float(cfg.get("session_wait_timeout_minutes", 720)) * 60
    # Every kernel ref of the manifest (full and smoke) per kind, so sessions still running from
    # earlier invocations count toward the limit.
    known = {kind: {f"{cfg['owner']}/{kernel_slug(n, sm)}"
                    for n in selected(manifest, None) if is_gpu(n) == kind for sm in (False, True)}
             for kind in (True, False)}
    for e in entries:
        slug = kernel_slug(e, args.smoke)
        kdir = out / "kernels" / slug
        if not kdir.is_dir():
            sys.exit(f"{kdir} not built; run `build{' --smoke' if args.smoke else ''}` first")
        gpu = is_gpu(e)
        limit = limits[gpu]
        wait = limit is not None and not args.no_wait
        kind = "GPU" if gpu else "CPU"
        cmd = ["kaggle", "kernels", "push", "-p", str(kdir)]
        if gpu and cfg.get("accelerator"):
            cmd += ["--accelerator", cfg["accelerator"]]
        if args.dry_run:
            run_cmd(cmd, True)
            srcs = source_refs(cfg, manifest, e)
            if srcs:
                print(f"# {slug}: kernel_sources {', '.join(srcs)} (must be COMPLETE before a real push)")
            continue
        while True:
            if wait:
                wait_slot(sorted(known[gpu] | set(pushed[gpu])), limit, interval, kind, wait_timeout)
            result = push_kernel(cmd)
            if result == "limit" and wait:
                print(f"{kind} session limit reported; retrying in {interval}s")
                time.sleep(interval)
                continue
            break
        if result == "ok":
            pushed[gpu].append(f"{cfg['owner']}/{slug}")
        else:
            failed.append(slug)
    if failed:
        print(f"error: {len(failed)} kernel push(es) failed: {', '.join(failed)}", file=sys.stderr)
        return 1
    return 0


def push_kernel(cmd):
    """Run a kernel push; "ok", "limit" (session limit reached) or "fail"."""
    print("$", " ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    text = (r.stdout or "") + (r.stderr or "")
    if text.strip():
        print(text.rstrip())
    low = text.lower()
    if "maximum batch" in low and "session" in low:
        return "limit"
    if r.returncode != 0 or "error" in text.lower():
        print(f"error: kernel push failed (rc={r.returncode})", file=sys.stderr)
        return "fail"
    return "ok"


def parse_kernel_status(text):
    """Status token of `kaggle kernels status` output, lower-case, or None if unparseable.

    >>> parse_kernel_status('irfancela/msc-thesis-complete has status "KernelWorkerStatus.RUNNING"')
    'running'
    >>> parse_kernel_status('a/b has status "COMPLETE"')
    'complete'
    >>> parse_kernel_status('irfancela/msc-thesis-complete: unknown') is None
    True
    """
    m = re.search(r'has status "(?:KernelWorkerStatus\.)?(\w+)"', text or "", re.I)
    return m.group(1).lower() if m else None


def classify_status_output(text, returncode=0):
    """Classify `kaggle kernels status` output as (status, reason).

    status is the lower-case token when parsed, else None; reason is None when parsed, else
    "rate limited", "not accessible" (never pushed or no permission) or "error".

    >>> classify_status_output('a/b has status "KernelWorkerStatus.RUNNING"')
    ('running', None)
    >>> classify_status_output("You have been rate limited. Wait a little while before retrying.", 1)
    (None, 'rate limited')
    >>> classify_status_output("Cannot access kernel 'a/b' (Permission 'kernels.get' was denied)", 1)
    (None, 'not accessible')
    >>> classify_status_output("boom", 1)
    (None, 'error')
    >>> classify_status_output("", 0)
    (None, 'error')
    """
    low = (text or "").lower()
    if "rate limited" in low:
        return None, "rate limited"
    st = parse_kernel_status(text) if returncode == 0 else None
    if st:
        return st, None
    if "cannot access kernel" in low:
        return None, "not accessible"
    return None, "error"


def kernel_status_ex(ref, sleep=time.sleep):
    """(status, reason) of a kernel; rate-limited calls are retried with bounded backoff."""
    for delay in (*STATUS_RETRY_DELAYS, None):
        r = subprocess.run(["kaggle", "kernels", "status", ref], capture_output=True, text=True)
        res = classify_status_output(r.stdout + "\n" + r.stderr, r.returncode)
        if res[1] != "rate limited" or delay is None:
            return res
        sleep(delay)


def kernel_status(ref):
    """Status token of a kernel, or None when unknown (see kernel_status_ex for the reason)."""
    return kernel_status_ex(ref)[0]


def active_sessions(refs, notes=None, status_fn=kernel_status_ex, sleep=time.sleep):
    """Number of the given kernels counting against the session limit.

    RUNNING/QUEUED count. Unreadable statuses (rate limited, errors) count as active
    (conservative) with a warning. Kernels Kaggle reports as not accessible (never pushed) are
    inactive for this call only; they are re-checked on every poll. `notes` (a list, if given)
    receives a description of each active or unreadable kernel.

    >>> res = {"a": ("running", None), "b": ("complete", None), "c": (None, "rate limited"),
    ...        "d": (None, "not accessible")}
    >>> notes = []
    >>> active_sessions(["a", "b", "c", "d"], notes, lambda r: res[r], lambda s: None)
    warning: could not read status of c (rate limited); counting it as active
    2
    >>> notes
    ['a (running)', 'c (unreadable: rate limited)']
    """
    n = 0
    for i, ref in enumerate(refs):
        if i:
            sleep(STATUS_CALL_SPACING)
        st, reason = status_fn(ref)
        if st is None and reason == "not accessible":
            continue
        if st is None:
            print(f"warning: could not read status of {ref} ({reason}); counting it as active")
            n += 1
            if notes is not None:
                notes.append(f"{ref} (unreadable: {reason})")
        elif st in ("running", "queued"):
            n += 1
            if notes is not None:
                notes.append(f"{ref} ({st})")
    return n


def check_sources_complete(cfg, manifest, entries, status_fn=kernel_status_ex):
    """Refuse to push a kernel whose kernel_sources are not COMPLETE on Kaggle (never auto-chain).

    Unreadable statuses are reported separately from parsed non-complete ones.
    """
    bad, unknown = [], []
    for e in entries:
        for ref in source_refs(cfg, manifest, e):
            st, reason = status_fn(ref)
            if st is None:
                unknown.append(f"{e['name']} needs {ref} ({reason} / error); retry later")
            elif st != "complete":
                bad.append(f"{e['name']} needs {ref} ({st})")
    if bad or unknown:
        msg = "error: "
        parts = []
        if bad:
            parts.append("source kernel(s) not COMPLETE on Kaggle: " + "; ".join(bad))
        if unknown:
            parts.append("could not read status of source kernel(s): " + "; ".join(unknown))
        sys.exit(msg + "; ".join(parts) + ". Wait for them (status), or pass --force to push anyway.")


def wait_slot(refs, limit, interval, kind="GPU", timeout=None, status_fn=kernel_status_ex,
              sleep=time.sleep, clock=time.monotonic):
    """Block until fewer than `limit` of `refs` are active; exit non-zero after `timeout` seconds.

    A timeout never allows the push.
    """
    deadline = None if timeout is None else clock() + timeout
    while True:
        notes = []
        n = active_sessions(refs, notes, status_fn, sleep)
        if n < limit:
            return
        if deadline is not None and clock() + interval > deadline:
            sys.exit(f"error: no {kind} session slot after {timeout}s ({n}/{limit} running, queued or unreadable: "
                     f"{', '.join(notes)}); check them with `status` or raise session_wait_timeout_minutes")
        print(f"waiting for a {kind} session slot: {n}/{limit} running or queued; next check in {interval}s")
        sleep(interval)


def cmd_status(args, manifest, cfg):
    rc = 0
    for e in selected(manifest, args.only):
        rc |= run_cmd(["kaggle", "kernels", "status", f"{cfg['owner']}/{kernel_slug(e, args.smoke)}"], False)
    return rc


def cmd_fetch(args, manifest, cfg):
    base = Path(args.out or "runs/kaggle")
    base = base if base.is_absolute() else REPO / base
    rc = 0
    for e in selected(manifest, args.only):
        slug = kernel_slug(e, args.smoke)
        dest = base / slug
        dest.mkdir(parents=True, exist_ok=True)
        rc |= run_cmd(["kaggle", "kernels", "output", f"{cfg['owner']}/{slug}", "-p", str(dest)], False)
    return rc


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(rn.DEFAULT_MANIFEST))
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn in (("build", cmd_build), ("push", cmd_push), ("status", cmd_status), ("fetch", cmd_fetch)):
        p = sub.add_parser(name)
        p.add_argument("--only")
        p.add_argument("--smoke", action="store_true", help="smoke kernels (suffix -smoke)")
        if name in ("build", "push", "fetch"):
            p.add_argument("--out")
        if name == "push":
            p.add_argument("--dry-run", action="store_true")
            p.add_argument("--no-wait", action="store_true", help="do not wait for free sessions")
            p.add_argument("--force", action="store_true", help="push even if source kernels are not COMPLETE")
            p.add_argument("--kernels-only", action="store_true", help="skip dataset create/version")
        p.set_defaults(fn=fn)
    args = ap.parse_args(argv)
    manifest = rn.load_manifest(args.manifest)
    return args.fn(args, manifest, kaggle_config(manifest))


if __name__ == "__main__":
    sys.exit(main())
